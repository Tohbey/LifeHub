package com.lifehub.starter.persistence;

import java.util.Objects;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Transient;

import org.springframework.data.domain.Persistable;

/**
 * Base class for entities whose UUIDv7 ID is generated in code before saving (ADR 0004). Implementing
 * {@link Persistable} tells Spring Data a new entity is new, so {@code save} inserts directly instead of
 * selecting first to decide between insert and update.
 */
@MappedSuperclass
public abstract class AssignedIdEntity implements Persistable<UUID> {

    @Id
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    @Transient
    private boolean isNew = true;

    /** For JPA only. */
    protected AssignedIdEntity() {
    }

    /** Creates a new entity with an ID generated by {@code Ids.newId()}. */
    protected AssignedIdEntity(UUID id) {
        this.id = Objects.requireNonNull(id);
    }

    /** The entity's UUIDv7 primary key. */
    @Override
    public UUID getId() {
        return id;
    }

    /** True until the entity has been saved or loaded, so Spring Data inserts instead of merging. */
    @Override
    public boolean isNew() {
        return isNew;
    }

    /** Called by JPA after loading or saving the entity. */
    @PostLoad
    @PostPersist
    void markNotNew() {
        isNew = false;
    }

    /** Two entities are equal when they are of the same class and have the same ID. */
    @Override
    public boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (other == null || getClass() != other.getClass()) {
            return false;
        }
        return id != null && id.equals(((AssignedIdEntity) other).id);
    }

    /** Constant per class, so the hash does not change when an entity is saved. */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}
